CREATE TABLE driver_push_deliveries (
    delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES driver_notification_events(event_id),
    recipient_account_id BIGINT NOT NULL REFERENCES identity_accounts(account_id),
    installation_id VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(24) NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'PROVIDER_ACCEPTED', 'FAILED', 'SKIPPED')),
    claim_id VARCHAR(64),
    lease_expires_at TIMESTAMPTZ,
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    provider_message_id TEXT,
    error_code VARCHAR(64),
    completed_at TIMESTAMPTZ,
    UNIQUE(event_id, installation_id),
    CHECK ((status = 'PROCESSING') = (claim_id IS NOT NULL AND lease_expires_at IS NOT NULL)),
    CHECK ((status IN ('PROVIDER_ACCEPTED', 'FAILED', 'SKIPPED')) = (completed_at IS NOT NULL)),
    CHECK ((status = 'PROVIDER_ACCEPTED') = (provider_message_id IS NOT NULL)),
    CHECK ((status = 'FAILED' AND error_code IS NOT NULL) OR (status <> 'FAILED' AND error_code IS NULL))
);
CREATE INDEX ix_driver_push_deliveries_pending ON driver_push_deliveries(created_at, delivery_id) WHERE status IN ('PENDING', 'PROCESSING');
