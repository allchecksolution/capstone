-- Separate account/session bindings support both administrator and driver apps.
-- Existing V1 administrator analysis tables remain immutable.
CREATE TABLE identity_push_devices (
    device_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id VARCHAR(64) NOT NULL CONSTRAINT uq_identity_push_devices_installation UNIQUE CHECK (char_length(btrim(installation_id)) > 0),
    account_id BIGINT NOT NULL REFERENCES identity_accounts(account_id),
    session_id BIGINT NOT NULL REFERENCES identity_auth_sessions(session_id),
    platform VARCHAR(10) NOT NULL CHECK (platform IN ('ANDROID', 'IOS')),
    push_token TEXT,
    token_hash VARCHAR(64),
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CHECK (updated_at >= created_at),
    CHECK ((revoked_at IS NULL AND push_token IS NOT NULL AND char_length(push_token) > 0
        AND token_hash IS NOT NULL AND token_hash = encode(sha256(convert_to(push_token, 'UTF8')), 'hex'))
        OR (revoked_at IS NOT NULL AND push_token IS NULL AND token_hash IS NULL))
);
CREATE UNIQUE INDEX uq_identity_push_devices_active_token ON identity_push_devices(token_hash) WHERE revoked_at IS NULL;
CREATE INDEX ix_identity_push_devices_account ON identity_push_devices(account_id) WHERE revoked_at IS NULL;
CREATE INDEX ix_identity_push_devices_session ON identity_push_devices(session_id) WHERE revoked_at IS NULL;
