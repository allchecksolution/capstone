-- Replace unused string keys without rewriting V1-V6 or guessing a mapping for existing IDs.
-- This migration is for empty tables only. Existing data requires a separately reviewed mapping.
-- Lock before checking so concurrent legacy inserts cannot pass the empty-table check.
LOCK TABLE receptions, reception_recordings, reception_transcripts, reception_analysis_requests, work_photos, admin_push_devices, reception_analysis_events, reception_analysis_push_deliveries IN ACCESS EXCLUSIVE MODE;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM receptions)
        OR EXISTS (SELECT 1 FROM reception_recordings)
        OR EXISTS (SELECT 1 FROM reception_transcripts)
        OR EXISTS (SELECT 1 FROM reception_analysis_requests)
        OR EXISTS (SELECT 1 FROM work_photos)
        OR EXISTS (SELECT 1 FROM admin_push_devices)
        OR EXISTS (SELECT 1 FROM reception_analysis_events)
        OR EXISTS (SELECT 1 FROM reception_analysis_push_deliveries) THEN
        RAISE EXCEPTION 'V7 requires empty ID-bearing tables; prepare an explicit ID mapping for existing data';
    END IF;
END
$$;

