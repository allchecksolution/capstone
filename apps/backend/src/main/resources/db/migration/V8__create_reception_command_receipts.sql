-- Successful reception command responses are operational retry receipts, not editable-data history.
-- No signed URL or AI/STT payload is stored by this table's supported commands.
CREATE TABLE reception_command_receipts (
    receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_admin_id BIGINT NOT NULL CHECK (actor_admin_id > 0),
    operation VARCHAR(30) NOT NULL CHECK (operation IN ('CREATE', 'CONFIRM', 'REOPEN')),
    scope_reception_id BIGINT NOT NULL CHECK (scope_reception_id >= 0),
    idempotency_key VARCHAR(200) NOT NULL CHECK (char_length(idempotency_key) > 0),
    request_fingerprint BYTEA NOT NULL CHECK (octet_length(request_fingerprint) = 32),
    result_reception_id BIGINT NOT NULL REFERENCES receptions(reception_id) ON DELETE RESTRICT,
    response_body JSONB NOT NULL CHECK (jsonb_typeof(response_body) = 'object'),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_reception_command_receipts_scope UNIQUE (actor_admin_id, operation, scope_reception_id, idempotency_key)
);
