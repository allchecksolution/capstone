ALTER TABLE identity_accounts ADD COLUMN is_bootstrap_admin BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE identity_accounts ADD CONSTRAINT ck_bootstrap_admin_active
    CHECK (NOT is_bootstrap_admin OR (user_type = 'ADMIN' AND enabled AND disabled_at IS NULL));
CREATE UNIQUE INDEX uq_bootstrap_admin ON identity_accounts (is_bootstrap_admin) WHERE is_bootstrap_admin;

-- Existing administrators are deliberately not promoted automatically.
CREATE TABLE identity_admin_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_account_id BIGINT REFERENCES identity_accounts(account_id),
    target_account_id BIGINT NOT NULL REFERENCES identity_accounts(account_id),
    action VARCHAR(40) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_admin_history_target ON identity_admin_history(target_account_id);

-- Application operations cannot remove the designated recovery identity.
CREATE FUNCTION protect_bootstrap_administrator() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.is_bootstrap_admin THEN
        IF TG_OP = 'DELETE' THEN
            RAISE EXCEPTION 'bootstrap administrator is protected';
        END IF;
        IF NOT NEW.is_bootstrap_admin THEN
            RAISE EXCEPTION 'bootstrap administrator designation is immutable';
        END IF;
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER protect_bootstrap_administrator
    BEFORE UPDATE OR DELETE ON identity_accounts
    FOR EACH ROW EXECUTE FUNCTION protect_bootstrap_administrator();
