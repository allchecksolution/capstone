-- The deployment role must be allowed to install PostGIS, or provision it beforehand.
CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA public;

CREATE TABLE service_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reception_id BIGINT NOT NULL UNIQUE REFERENCES receptions(reception_id),
    created_by_admin_id BIGINT NOT NULL CHECK (created_by_admin_id > 0),
    intake JSONB NOT NULL,
    site JSONB NOT NULL,
    site_point public.geography(Point,4326) GENERATED ALWAYS AS
        (public.ST_SetSRID(public.ST_MakePoint((site->>'longitude')::float8, (site->>'latitude')::float8),4326)::public.geography) STORED,
    status VARCHAR(30) NOT NULL CHECK (status IN ('OPEN','ACCEPTED','FOLLOW_UP_REQUIRED','COMPLETED','CANCELLED')),
    version INTEGER NOT NULL CHECK (version > 0),
    persistence_version BIGINT NOT NULL,
    current_round_id BIGINT,
    current_work_id BIGINT,
    follow_up_target JSONB,
    follow_up_reason VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CHECK ((site->>'longitude')::float8 BETWEEN -180 AND 180 AND (site->>'latitude')::float8 BETWEEN -90 AND 90),
    CHECK ((status = 'FOLLOW_UP_REQUIRED') = (follow_up_target IS NOT NULL AND follow_up_reason IS NOT NULL))
);
CREATE INDEX ix_service_requests_created ON service_requests(created_at DESC, request_id DESC);
CREATE INDEX ix_service_requests_site ON service_requests USING gist(site_point);

CREATE TABLE dispatch_rounds (
    round_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES service_requests(request_id),
    status VARCHAR(30) NOT NULL CHECK (status IN ('SEARCHING','OFFERING','ASSIGNED','NO_CANDIDATES','SEARCH_FAILED','DELIVERY_FAILED','NO_ACCEPT','ROUND_CLOSED')),
    radius_km INTEGER NOT NULL CHECK (radius_km IN (10,30,50)),
    created_at TIMESTAMPTZ NOT NULL,
    closed_at TIMESTAMPTZ,
    persistence_version BIGINT NOT NULL,
    UNIQUE(round_id,request_id),
    CHECK ((status IN ('SEARCHING','OFFERING')) = (closed_at IS NULL))
);
CREATE UNIQUE INDEX uq_dispatch_active_round ON dispatch_rounds(request_id) WHERE status IN ('SEARCHING','OFFERING');

CREATE TABLE dispatch_offers (
    offer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id BIGINT NOT NULL,
    request_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL CHECK (driver_id > 0),
    distance_meters DOUBLE PRECISION NOT NULL CHECK (distance_meters >= 0),
    status VARCHAR(30) NOT NULL CHECK (status IN ('PENDING','ACCEPTED','REJECTED','EXPIRED','RESPONSE_CLOSED')),
    delivery_status VARCHAR(30) NOT NULL CHECK (delivery_status IN ('PENDING','PROVIDER_ACCEPTED','FAILED')),
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL CHECK (expires_at > created_at),
    responded_at TIMESTAMPTZ,
    received_at TIMESTAMPTZ,
    viewed_at TIMESTAMPTZ,
    persistence_version BIGINT NOT NULL,
    UNIQUE(round_id,driver_id),
    UNIQUE(offer_id,round_id,request_id,driver_id),
    FOREIGN KEY(round_id,request_id) REFERENCES dispatch_rounds(round_id,request_id)
);
CREATE UNIQUE INDEX uq_dispatch_accepted_offer ON dispatch_offers(round_id) WHERE status='ACCEPTED';
CREATE INDEX ix_dispatch_offers_driver ON dispatch_offers(driver_id,created_at DESC,offer_id DESC);

CREATE TABLE work_orders (
    work_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES service_requests(request_id),
    round_id BIGINT NOT NULL UNIQUE REFERENCES dispatch_rounds(round_id),
    offer_id BIGINT NOT NULL UNIQUE,
    driver_id BIGINT NOT NULL CHECK (driver_id > 0),
    previous_work_id BIGINT REFERENCES work_orders(work_id),
    status VARCHAR(30) NOT NULL CHECK (status IN ('NOT_STARTED','EN_ROUTE','ARRIVED','IN_PROGRESS','REVISIT_REQUIRED','WORK_DONE','CANCELLED')),
    version INTEGER NOT NULL CHECK (version > 0),
    persistence_version BIGINT NOT NULL,
    events JSONB NOT NULL CHECK (jsonb_typeof(events)='array'),
    assigned_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    UNIQUE(work_id,request_id),
    FOREIGN KEY(offer_id,round_id,request_id,driver_id) REFERENCES dispatch_offers(offer_id,round_id,request_id,driver_id),
    CHECK ((status='WORK_DONE') = (completed_at IS NOT NULL)),
    CHECK ((status='CANCELLED') = (cancelled_at IS NOT NULL))
);
-- These guards remain effective without an idempotency receipt and across JVM instances.
CREATE UNIQUE INDEX uq_work_occupied_driver ON work_orders(driver_id) WHERE status NOT IN ('WORK_DONE','CANCELLED');
CREATE UNIQUE INDEX uq_work_active_request ON work_orders(request_id) WHERE status NOT IN ('WORK_DONE','CANCELLED');
CREATE INDEX ix_work_driver_assigned ON work_orders(driver_id,assigned_at DESC,work_id DESC);
CREATE INDEX ix_work_driver_completed ON work_orders(driver_id,completed_at DESC,work_id DESC) WHERE completed_at IS NOT NULL;
CREATE INDEX ix_work_driver_cancelled ON work_orders(driver_id,cancelled_at DESC,work_id DESC) WHERE cancelled_at IS NOT NULL;

ALTER TABLE service_requests ADD CONSTRAINT fk_request_round FOREIGN KEY(current_round_id,request_id) REFERENCES dispatch_rounds(round_id,request_id);
ALTER TABLE service_requests ADD CONSTRAINT fk_request_work FOREIGN KEY(current_work_id,request_id) REFERENCES work_orders(work_id,request_id);

CREATE TABLE work_cancellations (
    cancellation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id BIGINT NOT NULL UNIQUE,
    request_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL CHECK (driver_id > 0),
    reason_code VARCHAR(30) NOT NULL CHECK (reason_code IN ('SCHEDULE_CONFLICT','EQUIPMENT_UNAVAILABLE','TRAVEL_ISSUE','CUSTOMER_UNREACHABLE','OTHER')),
    reason_detail VARCHAR(1000) NOT NULL CHECK (char_length(btrim(reason_detail)) BETWEEN 1 AND 1000),
    previous_status VARCHAR(30) NOT NULL CHECK (previous_status IN ('NOT_STARTED','EN_ROUTE','ARRIVED','IN_PROGRESS','REVISIT_REQUIRED')),
    cancelled_at TIMESTAMPTZ NOT NULL,
    FOREIGN KEY(work_id,request_id) REFERENCES work_orders(work_id,request_id)
);
CREATE INDEX ix_cancelled_request_driver ON work_cancellations(request_id,driver_id);

CREATE TABLE operations_follow_up_decisions (
    decision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES service_requests(request_id),
    target JSONB NOT NULL,
    choice VARCHAR(30) NOT NULL CHECK (choice IN ('REDISPATCH','CANCEL_REQUEST')),
    admin_id BIGINT NOT NULL CHECK (admin_id > 0),
    new_round_id BIGINT REFERENCES dispatch_rounds(round_id),
    decided_at TIMESTAMPTZ NOT NULL,
    UNIQUE(request_id,target),
    CHECK ((choice='REDISPATCH') = (new_round_id IS NOT NULL))
);

ALTER TABLE work_photos ADD COLUMN persistence_version BIGINT NOT NULL DEFAULT 0;
-- Legacy metadata, if any, is retained. These checks enforce all new writes.
ALTER TABLE work_photos ADD CONSTRAINT fk_work_photos_work FOREIGN KEY(work_id) REFERENCES work_orders(work_id) NOT VALID;
ALTER TABLE work_photos ADD CONSTRAINT ck_work_photos_mvp CHECK (
    phase IN ('BEFORE','AFTER') AND content_type IN ('image/jpeg','image/png') AND size_bytes BETWEEN 1 AND 10000000
) NOT VALID;

CREATE TABLE work_reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id BIGINT NOT NULL UNIQUE REFERENCES work_orders(work_id),
    submitted_by_driver_id BIGINT NOT NULL CHECK (submitted_by_driver_id > 0),
    original JSONB NOT NULL,
    latest JSONB NOT NULL,
    before_photo_ids JSONB NOT NULL CHECK (jsonb_array_length(before_photo_ids) BETWEEN 3 AND 5),
    after_photo_ids JSONB NOT NULL CHECK (jsonb_array_length(after_photo_ids) BETWEEN 3 AND 5),
    version INTEGER NOT NULL CHECK (version > 0),
    persistence_version BIGINT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE work_report_revisions (
    revision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES work_reports(report_id),
    version INTEGER NOT NULL CHECK (version > 1),
    admin_id BIGINT NOT NULL CHECK (admin_id > 0),
    reason TEXT NOT NULL CHECK (char_length(btrim(reason)) > 0),
    before_content JSONB NOT NULL,
    after_content JSONB NOT NULL,
    revised_at TIMESTAMPTZ NOT NULL,
    UNIQUE(report_id,version)
);
