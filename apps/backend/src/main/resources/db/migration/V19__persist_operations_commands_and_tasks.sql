CREATE TABLE operations_receipts (
    receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_role VARCHAR(10) NOT NULL CHECK (actor_role IN ('ADMIN','DRIVER')),
    actor_id BIGINT NOT NULL CHECK (actor_id > 0),
    operation VARCHAR(40) NOT NULL,
    scope_id BIGINT NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL,
    fingerprint BYTEA NOT NULL CHECK (octet_length(fingerprint)=32),
    result JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE(actor_role,actor_id,operation,scope_id,idempotency_key)
);
CREATE TABLE operations_tasks (
    task_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(30) NOT NULL CHECK (kind IN ('SEARCH','EXPAND_OFFER','PUSH_OFFER','EXPAND_ADMIN','PUSH_ADMIN')),
    request_id BIGINT NOT NULL REFERENCES service_requests(request_id),
    subject_id BIGINT NOT NULL,
    logical_key VARCHAR(250) NOT NULL UNIQUE,
    actor_role VARCHAR(10) CHECK (actor_role IN ('ADMIN','DRIVER')),
    actor_id BIGINT CHECK (actor_id > 0),
    installation_id VARCHAR(200),
    state VARCHAR(30) NOT NULL CHECK (state IN ('PENDING','RUNNING','SUCCEEDED','FAILED','CANCELLED')),
    attempts INTEGER NOT NULL CHECK (attempts >= 0),
    due_at TIMESTAMPTZ NOT NULL,
    claim_token VARCHAR(36),
    lease_until TIMESTAMPTZ,
    persistence_version BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CHECK ((state='RUNNING') = (claim_token IS NOT NULL AND lease_until IS NOT NULL))
);
CREATE INDEX ix_operations_task_due ON operations_tasks(due_at,task_id) WHERE state='PENDING';
CREATE INDEX ix_operations_task_lease ON operations_tasks(lease_until,task_id) WHERE state='RUNNING';
CREATE INDEX ix_operations_task_subject ON operations_tasks(kind,subject_id);
